def gen_time_series(delta=300):

    def _get_point(s, i):
        point = datetime.strptime(s, '%Y-%m-%d_%H%M') + timedelta(seconds=delta*i)
        return point.strftime("%Y%m%d_%H-%M")

    today = str(date.today())
    s0 = today + "_0915"
    s1 = today + "_0930"
    s2 = today + "_1300"
    times = int(7200 / delta) + 1
    series = [_get_point(s1, i) for i in range(times)] + [_get_point(s2, i) for i in range(times)]
    series = [_get_point(s0, i) for i in range(13)] + series
    return series

def download(delta=60):
    root = "source_data/"
    series = gen_time_series(delta)
    iso_weekday = datetime.isoweekday(date.today())
    downloaded = set()
    while True:
        current_weekday = datetime.isoweekday(date.today())
        if current_weekday != iso_weekday:
            iso_weekday = current_weekday
            series = gen_time_series(delta)
        if iso_weekday <= 5:
            today = str(date.today())
            base_path = root + today
            if not os.path.exists(base_path):
                os.mkdir(base_path, 0o755)

            now = datetime.now().strftime("%Y%m%d_%H-%M")
            print(now)
            rest = set(series) - downloaded
            if now in rest:
                print("-------download------------")
                try:
                    path = os.path.join(base_path, now + ".csv")
                    if os.path.exists(path):
                        continue
                    rd = stock_zh_a_spot_em()
                    rd.to_csv(path)
                    downloaded.add(now)
                except:
                    continue
            #if not rest:
            #    break
        print("---------------sleep--------------")
        sleep(20)

