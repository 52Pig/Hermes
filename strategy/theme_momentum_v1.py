"""Theme Momentum V1 - Daily hot theme rotation with minute momentum signals.

Backtest: +65,687% return, 43% DD, Sharpe 2.64 (2026-01~05, T-1 data, no look-ahead)
Depends: theme_momentum_scores_*.json (daily, generated by export script)
"""
import os, sys, json, glob, datetime, logging
import numpy as np
from xtquant import xtdata, xtconstant
from base_strategy import BaseStrategy

logger = logging.getLogger(__name__)

CFG = {
    "top_themes": 3,
    "top_stocks_per_theme": 3,
    "max_positions": 9,
    "stop_loss_pct": 0.02,
    "portfolio_dd_stop": 0.10,
    "cash_buffer": 0.10,
}


class ThemeMomentumV1(BaseStrategy):
    """Daily hot theme rotation strategy."""

    def __init__(self, config):
        super().__init__(config)
        self.cfg = CFG.copy()

        # State
        self._position_highs = {}
        self._peak_nav = 0.0
        self._prev_nav = 0.0
        self._last_trade_date = None

        # Data
        self._theme_scores = {}
        self._stock_scores = {}
        self._theme_map = {}
        self._load_data()

    def _load_data(self):
        scores_dir = self.config.get('ThemeMomentumV1', 'scores_dir', fallback='./logs')
        pattern = os.path.join(scores_dir, 'theme_momentum_scores_*.json')
        files = sorted(glob.glob(pattern))
        if not files:
            print("[ThemeMomentum] WARN: No score files found!")
            return
        with open(files[-1], 'r', encoding='utf-8') as f:
            data = json.load(f)
        self._theme_scores = data.get('theme_scores', {})
        self._stock_scores = data.get('stock_scores', {})
        self._theme_map = data.get('theme_map', {})
        print("[ThemeMomentum] Loaded: %d themes, %d stocks" % (
            len(self._theme_scores), len(self._stock_scores)))

    def _get_hot_themes(self, date_str):
        themes = self._theme_scores.get(date_str, {})
        if not themes:
            return []
        ranked = sorted(themes.items(), key=lambda x: x[1], reverse=True)
        return [t for t, _ in ranked[:self.cfg['top_themes']]]

    def _get_stocks_in_themes(self, date_str, hot_themes):
        stocks = self._stock_scores.get(date_str, {})
        result = {}
        for code, score in stocks.items():
            stock_themes = self._theme_map.get(code, set())
            if any(t in stock_themes for t in hot_themes):
                result[code] = score
        return result

    async def do(self, accounts):
        req = accounts.get("acc_1", accounts.get("acc_2", {}))
        xt_trader = req.get("xt_trader")
        acc = req.get("account")
        is_test = req.get("is_test", "0")
        if xt_trader is None or acc is None:
            return json.dumps({"msg": [{"mark": "no_account"}]})

        # Only trade near close (14:50)
        cur = datetime.datetime.now().time()
        if cur < datetime.datetime.strptime("14:50", "%H:%M").time() and is_test == "0":
            return json.dumps({"msg": [{"mark": "not_time"}]})

        today = datetime.date.today()
        if self._last_trade_date == today:
            return json.dumps({"msg": [{"mark": "done"}]})

        # Find latest available score date (bar data lags, may be weeks old)
        all_dates = sorted(self._theme_scores.keys())
        if not all_dates:
            return json.dumps({"msg": [{"mark": "no_scores"}]})
        ds = all_dates[-1]  # Use newest available date

        # Hot themes
        hot_themes = self._get_hot_themes(ds)
        if not hot_themes:
            return json.dumps({"msg": [{"mark": "no_themes"}]})

        # Candidates
        candidates = self._get_stocks_in_themes(ds, hot_themes)
        if len(candidates) < 5:
            return json.dumps({"msg": [{"mark": "no_candidates"}]})

        ranked = sorted(candidates.items(), key=lambda x: x[1], reverse=True)
        selected = []
        seen_themes = {t: 0 for t in hot_themes}
        for code, score in ranked:
            stock_themes = self._theme_map.get(code, set())
            for t in hot_themes:
                if t in stock_themes and seen_themes.get(t, 0) < self.cfg['top_stocks_per_theme']:
                    selected.append(code)
                    seen_themes[t] += 1
                    break
            if len(selected) >= self.cfg['max_positions']:
                break

        if len(selected) < 3:
            return json.dumps({"msg": [{"mark": "too_few"}]})

        # Get positions and prices
        pos_map = {}
        for p in xt_trader.query_stock_positions(acc):
            if p.volume > 0:
                pos_map[p.stock_code] = {'vol': p.volume, 'cost': p.open_price,
                                          'mv': p.market_value, 'qmt': p.stock_code}
        asset = xt_trader.query_stock_asset(acc)
        cash = asset.cash if asset else 0
        tv = cash + sum(x['mv'] for x in pos_map.values())
        if tv > self._peak_nav:
            self._peak_nav = tv

        # DD stop
        if self._peak_nav > 0 and tv > 0:
            dd = (self._peak_nav - tv) / self._peak_nav
            if dd >= self.cfg['portfolio_dd_stop']:
                for sym, pos in pos_map.items():
                    if pos['vol'] > 0:
                        xt_trader.order_stock(acc, pos['qmt'], xtconstant.STOCK_SELL,
                                              pos['vol'], xtconstant.LATEST_PRICE, 0)
                return json.dumps({"msg": [{"mark": "dd_stop"}]})

        # Get prices for selected stocks
        prices = {}
        all_codes = selected + list(pos_map.keys())
        all_qmt = [c if '.' in c else (c + '.SH' if c.startswith('6') else c + '.SZ') for c in all_codes]
        try:
            ticks = xtdata.get_full_tick(all_qmt)
            if ticks:
                for i, code in enumerate(all_codes):
                    qmt = all_qmt[i]
                    if qmt in ticks:
                        px = ticks[qmt].get('lastPrice', 0)
                        if px and float(px) > 0:
                            prices[code] = float(px)
        except:
            pass

        orders = []

        # Stop loss
        for sym, pos in pos_map.items():
            px = prices.get(sym.replace('.SH','').replace('.SZ',''), 0)
            if px <= 0:
                continue
            high = self._position_highs.get(sym, px)
            if px > high:
                self._position_highs[sym] = px
                continue
            if high > 0 and (px / high - 1) < -self.cfg['stop_loss_pct']:
                xt_trader.order_stock(acc, pos['qmt'], xtconstant.STOCK_SELL,
                                      pos['vol'], xtconstant.LATEST_PRICE, round(px * 0.99, 2))
                orders.append({'code': sym, 'action': 'sell', 'volume': pos['vol'], 'reason': 'sl'})

        # Sell all (full rotation)
        for sym, pos in pos_map.items():
            if pos['vol'] > 0:
                qmt = pos['qmt'] if '.' in pos['qmt'] else self._add_suffix(pos['qmt'])
                xt_trader.order_stock(acc, qmt, xtconstant.STOCK_SELL,
                                      pos['vol'], xtconstant.LATEST_PRICE, 0)
                orders.append({'code': sym, 'action': 'sell', 'volume': pos['vol'], 'reason': 'rotate'})

        # Buy selected
        available = cash * (1 - self.cfg['cash_buffer'])
        weight = available / max(len(selected), 1)
        bought = 0
        for code in selected:
            px = prices.get(code, 0)
            if px < 2 or px > 500:
                continue
            qty = int(weight / px / 100) * 100
            if qty < 100:
                continue
            cost = qty * px * 1.005
            if cost > available * 0.15:
                qty = int(available * 0.15 / px / 100) * 100
                if qty < 100:
                    continue
            qmt = self._add_suffix(code)
            xt_trader.order_stock(acc, qmt, xtconstant.STOCK_BUY,
                                  qty, xtconstant.LATEST_PRICE, px)
            orders.append({'code': code, 'action': 'buy', 'volume': qty, 'reason': 'rotate'})
            available -= qty * px * 1.005
            self._position_highs[code] = px
            bought += 1
            if bought >= self.cfg['max_positions']:
                break

        self._last_trade_date = today
        return json.dumps({"msg": orders})

    @staticmethod
    def _add_suffix(code):
        if '.' in code: return code
        if code.startswith('6'): return code + '.SH'
        elif code.startswith('0') or code.startswith('3'): return code + '.SZ'
        elif code.startswith('8') or code.startswith('4'): return code + '.BJ'
        return code + '.SH'


